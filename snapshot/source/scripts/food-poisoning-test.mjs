import assert from 'node:assert/strict';
import fs from 'node:fs';
const data=JSON.parse(fs.readFileSync('food-poisoning/data/summary.json','utf8'));
const cases=data.meta.years.flatMap(y=>JSON.parse(fs.readFileSync(`food-poisoning/data/cases-${y}.json`,'utf8')));
const page=fs.readFileSync('food-poisoning/index.html','utf8');
const app=fs.readFileSync('food-poisoning/app.js','utf8');
const style=fs.readFileSync('food-poisoning/style.css','utf8');
assert.deepEqual(data.meta.years,[2011,2012,2013,2014,2015,2016,2017,2018,2019,2020,2021,2022,2023,2024,2025]);
assert.equal(data.meta.latest,2025);
assert.equal(cases.length,15654);
assert.equal(data.annual.length,15);
assert.ok(data.annual.every(a=>a.prefectures.length===47));
assert.deepEqual(Object.fromEntries(data.annual.filter(a=>a.year>=2023).map(a=>[a.year,[a.events,a.patients,a.deaths]])),{2023:[1021,11803,4],2024:[1037,14229,3],2025:[1172,24727,2]});
assert.match(page,/事件数が多い原因と、一度に多くの患者/);
assert.match(page,/多い県ほど衛生状態が悪いとは限りません/);
assert.match(page,/公式総数と事例票/);
assert.match(app,/発生事例票には/);
for(let i=0;i<7;i++)assert.match(style,new RegExp(`\\.swatch-${i}\\{background:`));
console.log('food-poisoning data and interface: ok');
