import assert from 'node:assert/strict';
import {formatExpected,trendDisplay} from '../src/lib/smrDisplay.js';
import {annualSmrTrend,officialSmrTrend} from '../src/lib/trend.js';
import {medicalAreaTrend} from '../src/lib/medicalAreas.js';
import {smrWith95CI} from '../src/lib/smr.js';
for(const [input,output] of [[null,'—'],[NaN,'—'],[0,'0.0'],[0.00001,'0.1未満'],[0.049,'0.1未満'],[0.099,'0.1未満'],[0.1,'0.1'],[9981.188,'9,981.2']])assert.equal(formatExpected(input),output);
const data={rows:[[2020,'05201','M',0,0.01],[2022,'05201','M',5,4],[2023,'05201','M',null,4],[2024,'05201','M',7,8]]};
const annual=annualSmrTrend(data,{areaCode:'05201',sex:'男',startYear:2020,endYear:2024});
assert.deepEqual(annual.map(p=>p.year),[2020,2021,2022,2023,2024]);
assert.deepEqual(annual.map(p=>p.smr),[0,null,125,null,87.5]);
assert.equal(annual[0].ci95High,smrWith95CI(0,0.01).ci95High);
assert.equal(annual[0].expected,0.01);
const display=trendDisplay(annual);
assert.deepEqual(display.segments.map(s=>s.map(p=>p.year)),[[2020],[2022],[2024]]);
assert.deepEqual(display.points.map(display.fraction),[0,.25,.5,.75,1]);
const sparse=trendDisplay([annual[0],annual[2],annual[4]]);
assert.equal(sparse.segments.length,3);
assert.deepEqual(sparse.points.map(sparse.fraction),[0,.5,1]);
const medical=medicalAreaTrend(data,{municipalities:[['05201','秋田市']]},'男');
assert.equal(medical.length,26);assert.equal(medical.find(p=>p.year===2021).smr,null);assert.equal(medical.at(-1).smr,87.5);
const both=annualSmrTrend(data,{areaCode:'05201',sex:'男女計',startYear:2020,endYear:2024});assert(both.every(p=>p.smr===null));
const official=officialSmrTrend({rows:[[1998,2002,'05201','秋田市','男',null,null,5,90,null],[2008,2012,'05201','秋田市','男',null,null,7,110,null]]},{areaCode:'05201',sex:'男'});
assert.equal(official.length,5);assert.equal(official[1].value,null);assert.equal(trendDisplay(official,true).segments.length,2);
assert.equal(trendDisplay([{year:2024,smr:0}]).fraction({year:2024}),.5);
assert.deepEqual(trendDisplay(both).segments,[]);
assert.equal(trendDisplay([]).points.length,0);
console.log('PASS: missing years/periods, calendar spacing, zero deaths, all missing, medical area, both-sex missingness and small expected counts');
